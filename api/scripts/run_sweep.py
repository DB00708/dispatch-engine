"""Run the scarcity sweep and write docs/algorithm-comparison-results.md.

    python -m scripts.run_sweep            # 30 tickets, ratios 0.3-1.5, 20 seeds
    python -m scripts.run_sweep --seeds 50

Numbers in the write-up come from this script, so they always match the code.
"""

from __future__ import annotations

import argparse
import time
from collections import defaultdict
from pathlib import Path

from app.config import get_settings
from app.domain.models import AllocationConfig
from app.engine.allocators.registry import ALGORITHM_NAMES
from app.engine.sweep import SweepPoint, run_sweep
from app.estimators.naive import NaiveEstimator

RATIOS = (0.3, 0.5, 0.75, 1.0, 1.25, 1.5)
# The write-up lives in the repository root: <repo>/docs/.
OUTPUT = Path(__file__).resolve().parents[2] / "docs" / "algorithm-comparison-results.md"


def _fmt(value: float | None, digits: int = 1, suffix: str = "") -> str:
    return "n/a" if value is None else f"{value:.{digits}f}{suffix}"


def render(points: list[SweepPoint], tickets: int, seeds: int, seconds: float) -> str:
    by_ratio: dict[float, dict[str, SweepPoint]] = defaultdict(dict)
    for point in points:
        by_ratio[point.ratio][point.algorithm] = point

    lines = [
        "# Scarcity sweep results",
        "",
        f"Generated by `python -m scripts.run_sweep` with {tickets} tickets, "
        f"{seeds} seeds per ratio, default weights (distance 1.0, slack 0.5), 30 km limit, "
        f"30 km/h. Total run time {seconds:.1f} s.",
        "",
        "Gap = how much higher an algorithm's objective is than the best one in the same "
        "scenario (Hungarian is optimal, so the best is always Hungarian).",
        "",
        "| Ratio | Engineers | Algorithm | Mean objective | Mean gap | p90 gap | Coverage | "
        "P1 coverage | Runtime |",
        "| ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for ratio in sorted(by_ratio):
        for name in ALGORITHM_NAMES:
            p = by_ratio[ratio].get(name)
            if p is None:
                continue
            lines.append(
                f"| {ratio:g} | {p.num_engineers} | {name} | {p.mean_objective:.1f} | "
                f"{_fmt(p.mean_gap_pct, 1, '%')} | "
                f"{_fmt(p.p90_gap_pct, 1, '%')} | {_fmt(p.mean_coverage_pct, 1, '%')} | "
                f"{_fmt(p.mean_p1_coverage_pct, 1, '%')} | {p.mean_runtime_ms:.2f} ms |"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tickets", type=int, default=30)
    parser.add_argument("--seeds", type=int, default=20)
    args = parser.parse_args()

    settings = get_settings()
    started = time.perf_counter()
    points = run_sweep(
        num_tickets=args.tickets,
        ratios=RATIOS,
        seeds_per_ratio=args.seeds,
        algorithms=ALGORITHM_NAMES,
        config=AllocationConfig(),
        estimator=NaiveEstimator(),
        dispatch_time=settings.default_dispatch_time,
        road_factor=settings.road_factor,
        tight_slack_min=settings.tight_slack_min,
    )
    report = render(points, args.tickets, args.seeds, time.perf_counter() - started)
    OUTPUT.write_text(report, encoding="utf-8")
    print(report)
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
